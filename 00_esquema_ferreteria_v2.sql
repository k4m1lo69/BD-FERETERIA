DROP TABLE IF EXISTS reportes CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS pagos CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS detalle_pedidos CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS pedidos CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS inventarios CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS productos CASCADE CONSTRAINTS;
DROP TABLE IF EXISTS marcas CASCADE CONSTRAINTS;
