DROP TRIGGER IF EXISTS trg_auditoria_pedido;
DROP TRIGGER IF EXISTS trg_alerta_stock_critico;
DROP TRIGGER IF EXISTS trg_valida_stock_negativo;
DROP PACKAGE IF EXISTS pkg_gestion_pedidos;
DROP PROCEDURE IF EXISTS sp_registrar_pedido;
DROP FUNCTION IF EXISTS fn_calcular_total_pedido;
